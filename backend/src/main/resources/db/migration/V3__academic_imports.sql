-- V3: student-controlled academic import — consent, import batches, attendance snapshots, exam results.
--
-- Safety design is identical to V2 (see docs/database-migrations.md):
--   * One PostgreSQL transaction; any RAISE rolls everything back and the old app keeps serving.
--   * Step 0 verifies the live schema is what this migration expects before changing anything.
--   * Step 1 fingerprints every pre-existing table (row count + md5 over each row's JSON, ignoring the
--     one new column this migration adds); step 5 recomputes and aborts if any pre-existing value changed.
--   * Only additive: new tables, and one nullable column on marks. No DROP / TRUNCATE / DELETE / UPDATE
--     of existing data.

-- ---------------------------------------------------------------------------------------------
-- 0. Preconditions
-- ---------------------------------------------------------------------------------------------
DO $$
DECLARE
    missing text;
BEGIN
    SELECT string_agg(req.t || '.' || req.c, ', ') INTO missing
    FROM (VALUES ('students','user_id'), ('courses','id'), ('marks','id')) AS req(t, c)
    WHERE NOT EXISTS (SELECT 1 FROM information_schema.columns ic
                      WHERE ic.table_schema = current_schema() AND ic.table_name = req.t AND ic.column_name = req.c);
    IF missing IS NOT NULL THEN
        RAISE EXCEPTION 'V3 precondition failed: missing columns %', missing;
    END IF;

    IF EXISTS (SELECT 1 FROM information_schema.tables
               WHERE table_schema = current_schema()
                 AND table_name IN ('academic_import_batches','attendance_snapshots','exam_results','student_data_consents')) THEN
        RAISE EXCEPTION 'V3 precondition failed: an import table already exists';
    END IF;
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = current_schema() AND table_name = 'marks' AND column_name = 'import_batch_id') THEN
        RAISE EXCEPTION 'V3 precondition failed: marks.import_batch_id already exists';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'students'::regclass AND contype IN ('p','u')
                   AND conkey = ARRAY[(SELECT attnum FROM pg_attribute WHERE attrelid = 'students'::regclass AND attname = 'user_id')]) THEN
        RAISE EXCEPTION 'V3 precondition failed: students.user_id is not a primary/unique key';
    END IF;
END $$;

-- ---------------------------------------------------------------------------------------------
-- 1. Fingerprint every pre-existing table (ignore the new column V3 adds to marks)
-- ---------------------------------------------------------------------------------------------
CREATE TEMP TABLE v3_fingerprint (table_name text PRIMARY KEY, row_count bigint, digest text) ON COMMIT DROP;

DO $$
DECLARE
    tbl text;
    cnt bigint;
    dig text;
BEGIN
    FOR tbl IN SELECT table_name FROM information_schema.tables
               WHERE table_schema = current_schema() AND table_type = 'BASE TABLE'
                 AND table_name NOT IN ('flyway_schema_history')
    LOOP
        EXECUTE format('SELECT count(*), md5(coalesce(string_agg(j, ''|'' ORDER BY j), '''')) '
                    || 'FROM (SELECT (to_jsonb(x) - ''import_batch_id'')::text AS j FROM %I x) s', tbl)
            INTO cnt, dig;
        INSERT INTO v3_fingerprint VALUES (tbl, cnt, dig);
    END LOOP;
END $$;

-- ---------------------------------------------------------------------------------------------
-- 2. Consent (purpose-specific, revocable)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE student_data_consents (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id     BIGINT NOT NULL REFERENCES students(user_id),
    purpose        VARCHAR(64) NOT NULL,
    policy_version VARCHAR(16) NOT NULL,
    granted_at     TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at     TIMESTAMP(6) WITHOUT TIME ZONE
);
CREATE INDEX idx_consents_student ON student_data_consents (student_id);

-- ---------------------------------------------------------------------------------------------
-- 3. Import batches (one student upload). content_sha256 gives duplicate-upload detection.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE academic_import_batches (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id     BIGINT NOT NULL REFERENCES students(user_id),
    source_type    VARCHAR(32) NOT NULL,       -- STUDENT_MANUAL_IMPORT
    report_type    VARCHAR(32),                -- ATTENDANCE | EXAM_LEDGER | MIXED
    report_date    DATE,
    uploaded_at    TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    content_sha256 VARCHAR(64),
    status         VARCHAR(16) NOT NULL,        -- PREVIEW | CONFIRMED | DISCARDED
    accepted_rows  INT NOT NULL DEFAULT 0,
    rejected_rows  INT NOT NULL DEFAULT 0,
    CONSTRAINT uk_import_batch_content UNIQUE (student_id, content_sha256)
);
CREATE INDEX idx_import_batches_student ON academic_import_batches (student_id);

-- ---------------------------------------------------------------------------------------------
-- 4. Attendance snapshots (dated aggregate; replaces fabricated per-day rows) and exam results
-- ---------------------------------------------------------------------------------------------
CREATE TABLE attendance_snapshots (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  BIGINT NOT NULL REFERENCES students(user_id),
    course_id   BIGINT NOT NULL REFERENCES courses(id),
    batch_id    BIGINT REFERENCES academic_import_batches(id),
    as_of_date  DATE NOT NULL,
    conducted   INT NOT NULL,
    present     INT NOT NULL,
    absent      INT NOT NULL,
    od_ml       INT NOT NULL DEFAULT 0,
    CONSTRAINT uk_attendance_snapshot UNIQUE (student_id, course_id, as_of_date)
);
CREATE INDEX idx_attendance_snapshots_student ON attendance_snapshots (student_id);

CREATE TABLE exam_results (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id   BIGINT NOT NULL REFERENCES students(user_id),
    course_id    BIGINT NOT NULL REFERENCES courses(id),
    batch_id     BIGINT REFERENCES academic_import_batches(id),
    semester     VARCHAR(32) NOT NULL,
    month_year   VARCHAR(16),
    credit       DOUBLE PRECISION,
    grade        VARCHAR(4),
    grade_points DOUBLE PRECISION,
    result       VARCHAR(16),
    attempt      INT NOT NULL DEFAULT 1,
    CONSTRAINT uk_exam_result UNIQUE (student_id, course_id, semester, attempt)
);
CREATE INDEX idx_exam_results_student ON exam_results (student_id);

-- Link imported marks to their batch (existing table, additive nullable column).
ALTER TABLE marks ADD COLUMN import_batch_id BIGINT REFERENCES academic_import_batches(id);

-- ---------------------------------------------------------------------------------------------
-- 5. Verify no pre-existing data changed; abort (full rollback) otherwise
-- ---------------------------------------------------------------------------------------------
DO $$
DECLARE
    fp record;
    cnt bigint;
    dig text;
BEGIN
    FOR fp IN SELECT * FROM v3_fingerprint LOOP
        EXECUTE format('SELECT count(*), md5(coalesce(string_agg(j, ''|'' ORDER BY j), '''')) '
                    || 'FROM (SELECT (to_jsonb(x) - ''import_batch_id'')::text AS j FROM %I x) s', fp.table_name)
            INTO cnt, dig;
        IF cnt <> fp.row_count OR dig <> fp.digest THEN
            RAISE EXCEPTION 'V3 data-preservation check failed for table % (rows % -> %)', fp.table_name, fp.row_count, cnt;
        END IF;
    END LOOP;
    RAISE NOTICE 'V3 data-preservation check passed for % tables', (SELECT count(*) FROM v3_fingerprint);
END $$;
