-- V2: explicit faculty-course assignments, stored student data provenance, extensible roles.
--
-- Safety design (reviewed in docs/database-migrations.md):
--   * Flyway runs this file in ONE PostgreSQL transaction. Any RAISE or error rolls back everything,
--     the old application version keeps serving, and nothing is recorded as applied.
--   * Step 0 verifies the live schema matches what this migration expects before changing anything.
--   * Step 1 fingerprints every pre-existing table (row count + md5 over each row's JSON);
--     step 5 recomputes and aborts if any pre-existing value changed. The only permitted writes are
--     to the new column students.data_provenance and the new table course_assignments.
--   * No DROP TABLE / DROP COLUMN / TRUNCATE / DELETE. Only a role CHECK constraint is replaced
--     by a strictly wider one (no row can violate it).

-- ---------------------------------------------------------------------------------------------
-- 0. Preconditions
-- ---------------------------------------------------------------------------------------------
DO $$
DECLARE
    missing text;
BEGIN
    SELECT string_agg(req.t || '.' || req.c, ', ') INTO missing
    FROM (VALUES ('users','id'), ('users','username'), ('users','role'), ('users','auth_provider'),
                 ('students','user_id'), ('students','student_number'),
                 ('faculty','user_id'), ('courses','id'), ('courses','code')) AS req(t, c)
    WHERE NOT EXISTS (SELECT 1 FROM information_schema.columns ic
                      WHERE ic.table_schema = current_schema() AND ic.table_name = req.t AND ic.column_name = req.c);
    IF missing IS NOT NULL THEN
        RAISE EXCEPTION 'V2 precondition failed: missing columns %', missing;
    END IF;

    IF EXISTS (SELECT 1 FROM information_schema.tables
               WHERE table_schema = current_schema() AND table_name = 'course_assignments') THEN
        RAISE EXCEPTION 'V2 precondition failed: table course_assignments already exists';
    END IF;
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = current_schema() AND table_name = 'students' AND column_name = 'data_provenance') THEN
        RAISE EXCEPTION 'V2 precondition failed: students.data_provenance already exists';
    END IF;

    -- FK targets must be unique keys.
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'faculty'::regclass AND contype IN ('p','u')
                   AND conkey = ARRAY[(SELECT attnum FROM pg_attribute WHERE attrelid = 'faculty'::regclass AND attname = 'user_id')]) THEN
        RAISE EXCEPTION 'V2 precondition failed: faculty.user_id is not a primary/unique key';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'courses'::regclass AND contype IN ('p','u')
                   AND conkey = ARRAY[(SELECT attnum FROM pg_attribute WHERE attrelid = 'courses'::regclass AND attname = 'id')]) THEN
        RAISE EXCEPTION 'V2 precondition failed: courses.id is not a primary/unique key';
    END IF;

    -- Every current role value must be allowed by the new constraint.
    IF EXISTS (SELECT 1 FROM users WHERE role NOT IN ('ADMIN','FACULTY','STUDENT','MENTOR','HOD','GUARDIAN')) THEN
        RAISE EXCEPTION 'V2 precondition failed: users contains an unexpected role value';
    END IF;
END $$;

-- ---------------------------------------------------------------------------------------------
-- 1. Fingerprint every pre-existing table
-- ---------------------------------------------------------------------------------------------
CREATE TEMP TABLE v2_fingerprint (table_name text PRIMARY KEY, row_count bigint, digest text) ON COMMIT DROP;

DO $$
DECLARE
    tbl text;
    cnt bigint;
    dig text;
BEGIN
    FOR tbl IN SELECT table_name FROM information_schema.tables
               WHERE table_schema = current_schema() AND table_type = 'BASE TABLE'
                 AND table_name NOT IN ('flyway_schema_history')
    LOOP
        EXECUTE format('SELECT count(*), md5(coalesce(string_agg(j, ''|'' ORDER BY j), '''')) '
                    || 'FROM (SELECT (to_jsonb(x) - ''data_provenance'')::text AS j FROM %I x) s', tbl)
            INTO cnt, dig;
        INSERT INTO v2_fingerprint VALUES (tbl, cnt, dig);
    END LOOP;
END $$;

-- ---------------------------------------------------------------------------------------------
-- 2. Faculty <-> course assignments (replaces username-based course guessing)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE course_assignments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id  BIGINT NOT NULL REFERENCES faculty(user_id),
    course_id   BIGINT NOT NULL REFERENCES courses(id),
    section     VARCHAR(64),
    term        VARCHAR(32),
    created_at  TIMESTAMP(6) WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_course_assignment
    ON course_assignments (faculty_id, course_id, COALESCE(section, ''), COALESCE(term, ''));
CREATE INDEX idx_course_assignments_course ON course_assignments (course_id);

-- Backfill only the two DEMO showcase faculty (preserves current showcase behaviour).
INSERT INTO course_assignments (faculty_id, course_id)
SELECT f.user_id, c.id
FROM faculty f
JOIN users u ON u.id = f.user_id AND u.auth_provider = 'DEMO'
JOIN courses c ON (u.username = 'demo.faculty.1' AND c.code = 'CSE 204')
               OR (u.username = 'demo.faculty.2' AND c.code = 'CSE 213');

-- ---------------------------------------------------------------------------------------------
-- 3. Stored data provenance (nullable; NULL = unspecified / legacy record)
-- ---------------------------------------------------------------------------------------------
ALTER TABLE students ADD COLUMN data_provenance VARCHAR(64);

UPDATE students s SET data_provenance = 'STUDENT_SUPPLIED_REFERENCE'
FROM users u
WHERE s.user_id = u.id AND u.auth_provider = 'DEMO' AND s.student_number = 'STU-1001';

UPDATE students s SET data_provenance = 'SYNTHETIC_TEST_FIXTURE'
FROM users u
WHERE s.user_id = u.id AND u.auth_provider = 'DEMO' AND s.student_number IN ('STU-1002', 'STU-1003', 'STU-1004');

-- ---------------------------------------------------------------------------------------------
-- 4. Widen the role CHECK constraint (Phase 10 roles). No account is granted a new role.
--    The old constraint may carry a Hibernate- or pg_dump-generated name, so match by definition.
-- ---------------------------------------------------------------------------------------------
DO $$
DECLARE
    con record;
BEGIN
    FOR con IN SELECT conname FROM pg_constraint
               WHERE conrelid = 'users'::regclass AND contype = 'c'
                 AND pg_get_constraintdef(oid) ILIKE '%role%'
    LOOP
        EXECUTE format('ALTER TABLE users DROP CONSTRAINT %I', con.conname);
    END LOOP;
END $$;
ALTER TABLE users ADD CONSTRAINT users_role_check
    CHECK (role IN ('ADMIN', 'FACULTY', 'STUDENT', 'MENTOR', 'HOD', 'GUARDIAN'));

-- ---------------------------------------------------------------------------------------------
-- 5. Verify no pre-existing data changed; abort (full rollback) otherwise
-- ---------------------------------------------------------------------------------------------
DO $$
DECLARE
    fp record;
    cnt bigint;
    dig text;
BEGIN
    FOR fp IN SELECT * FROM v2_fingerprint LOOP
        EXECUTE format('SELECT count(*), md5(coalesce(string_agg(j, ''|'' ORDER BY j), '''')) '
                    || 'FROM (SELECT (to_jsonb(x) - ''data_provenance'')::text AS j FROM %I x) s', fp.table_name)
            INTO cnt, dig;
        IF cnt <> fp.row_count OR dig <> fp.digest THEN
            RAISE EXCEPTION 'V2 data-preservation check failed for table % (rows % -> %)', fp.table_name, fp.row_count, cnt;
        END IF;
    END LOOP;
    RAISE NOTICE 'V2 data-preservation check passed for % tables', (SELECT count(*) FROM v2_fingerprint);
END $$;
